def _spread_path():
    """示意用的價差 z 路徑（決定性、非真實資料）。"""
    ctrl = [(0, 0.1), (12, 0.3), (28, 2.25), (36, 2.6), (44, 1.6), (56, -0.05),
            (66, 0.35), (76, -0.4), (92, -2.2), (104, -2.7), (116, -3.1),
            (126, -3.35)]
    zs = []
    for t in range(127):
        for (t0, z0), (t1, z1) in zip(ctrl, ctrl[1:]):
            if t0 <= t <= t1:
                u = (t - t0) / (t1 - t0)
                u = (1 - math.cos(math.pi * u)) / 2
                base = z0 + (z1 - z0) * u
                break
        noise = 0.16 * math.sin(t * 0.9) + 0.10 * math.sin(t * 2.3 + 1.0) \
            + 0.07 * math.sin(t * 4.1 + 0.5)
        zs.append(base + noise)
    return zs


