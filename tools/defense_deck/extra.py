def _em(s):
    return sum(1.0 if ord(c) > 0x2E7F else 0.5 for c in s)


REF_SIZE = 11.5
REF_LINE_EM = 66          # 一行可容納的全形字數（保守估計）
REF_LINE_H = 0.20         # 行高（英吋）
REF_BUDGET = 4.75         # 每頁可用高度（英吋）


def _paginate(groups):
    pages, cur, used = [], [], 0.0
    for head, entries in groups:
        items = [{"text": head, "size": 12.5, "bold": True, "color": NAVY,
                  "after": 4}] + list(entries)
        for it in items:
            if isinstance(it, dict):
                h = 0.27
            else:
                plain = re.sub(r"\*\*|\{\{|\}\}", "", it)
                h = math.ceil(_em(plain) / REF_LINE_EM) * REF_LINE_H + 0.075
            if cur and used + h > REF_BUDGET:
                pages.append(cur)
                cur, used = [], 0.0
            cur.append(it)
            used += h
    if cur:
        pages.append(cur)
    return pages


