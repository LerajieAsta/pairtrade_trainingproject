@reg(0)
def b_index(d):
    s = d.slide()
    text(s, LEFT, 0.55, CONTENT_W, 0.9, "備用投影片", size=30, bold=True, color=NAVY)
    y = 1.65
    for i, (code, name, ref) in enumerate(BACKUPS):
        col = 0 if i < 7 else 1
        yy = y + (i % 7) * 0.66
        x = LEFT + col * 6.1
        text(s, x, yy, 0.8, 0.5, code, size=16, bold=True, color=ACCENT)
        text(s, x + 0.85, yy, 5.1, 0.7, [
            {"text": name, "size": 15, "bold": True, "color": NAVY, "after": 0},
            {"text": ref, "size": 12, "color": GREY}], space_after=0)
    page_number(s, d.n)
    return "以下為備用投影片，問答時依問題翻到對應頁。"


