@reg(0.75)
def rolling(d):
    s = std(d, sec("3.1.3"), "滾動回測：任何一天，都有 6 個交易期同時在跑")
    table(s, LEFT, 1.85, [2.4, 2.9], [
        ["參數", "設定"],
        ["形成期", "252 個交易日"],
        ["交易期", "126 個交易日"],
        ["滾動步長", "21 個交易日（約一個月）"],
        ["同時重疊期數", "**6**（＝126 ÷ 21）"],
        ["滾動期數", "295 期"],
    ], size=15, row_h=0.42)
    # 重疊示意：形成期以 0.3 倍壓縮顯示，交易期與步長照實際比例
    x0, y0 = 6.55, 1.95
    fdays = 252 * 0.3
    u = 6.0 / (6 * 21 + fdays + 126)
    text(s, x0, y0 - 0.05, 6.0, 0.3, "示意：每 21 天開一個新的交易期", size=12,
         bold=True, color=NAVY)
    for k in range(7):
        yy = y0 + 0.40 + k * 0.38
        fx = x0 + k * 21 * u
        box(s, fx, yy, fdays * u, 0.26, None, fill="C9D3E3", shape="rect")
        box(s, fx + fdays * u, yy, 126 * u, 0.26, None,
            fill=(ACCENT if k < 6 else "E7B2A5"), shape="rect")
    xt = x0 + (5 * 21 + fdays + 10) * u
    line_seg(s, xt, y0 + 0.30, xt, y0 + 0.40 + 7 * 0.38, color=NAVY, width=1.5,
             dash=True)
    text(s, x0, y0 + 3.20, 6.0, 0.6, [
        "灰：形成期（壓縮顯示）　紅：交易期",
        "虛線那一天，有 6 個交易期同時持有部位；第 7 期要等第 1 期結束才開始"],
        size=12, color=GREY, space_after=2)
    callout(s, LEFT, 4.50, 5.3, 2.10, "這個設計帶來三個後果",
            ["① 逐期報酬**自我相關** → 檢定要用區塊自助法",
             "② 天天決定的動作空間，一期最多 **126 次**",
             "③ 同一配對可被多期**同時持有**（約 37%）→ 分批加碼"],
            style="light", size=13.5)
    return """
回測是滾動的。形成期 252 天、交易期 126 天，每 21 天往前滾一次，整段樣本一共 295 期。

右邊是示意圖。每一條是一個期：灰色是形成期，紅色是交易期。因為每 21 天就開一個新的交易期，而一個交易期要跑 126 天，所以你拉一條垂直線，像虛線這一天，會看到有 6 個交易期同時持有部位。

這個設計有三個後果，後面都會用到。第一，相鄰期的報酬是重疊的，所以逐期報酬序列有結構性的自我相關——這決定了我的統計檢定不能用一般的 t 檢定，要用區塊自助法。第二，因為交易期是 126 天，所以天天決定的動作空間，一期最多就是 126 次決策。這就是剛剛那個 126 的來源。

〔可略〕第三個後果是我後來才量到的：同一組配對如果連續幾期都被選中，就會被好幾個期同時持有、各拿一份資金，大約 37% 的部位是這種跨期重複。這是 GGR 重疊組合的標準設計，不是錯誤，但它有功能：較晚那一份是在價差更偏離的時候才進場，等於分批加碼。我做過預先登記的去重實驗，把重複拿掉，60 格裡有 58 格的 Sharpe 反而下降，細節在附錄 G。
"""


@reg(1.0)
def four_layers(d):
    s = std(d, sec("3.2.1"), "形成期拆成四層，每一層都可以單獨換掉")
    layers = [("1　特徵萃取", ["19 維", "報酬 PCA 5 維", "市值、盈餘殖利率", "GICS one-hot"]),
              ("2　分組", ["5 個配對來源", "不分組／GICS", "HDBSCAN", "Agglomerative／K-means"]),
              ("3　統計篩選", ["Engle-Granger 共整合", "ADF 殘差檢定", "MacKinnon 臨界值"]),
              ("4　群內排序", ["SSD／DTW／SDP", "取距離最小的", "前 N 組"])]
    x = LEFT
    for i, (head, lines) in enumerate(layers):
        col = ACCENT if i == 1 else NAVY
        box(s, x, 1.95, 2.75, 2.45, [{"text": head, "size": 17, "bold": True,
                                      "color": WHITE, "after": 8}] +
            [{"text": t, "size": 13.5, "color": WHITE, "after": 2} for t in lines],
            fill=col)
        if i < 3:
            arrow(s, x + 2.77, 3.17, x + 3.03, 3.17, color=GREY, width=2.0)
        x += 3.05
    callout(s, LEFT, 4.70, 5.75, 1.6, "為什麼篩選要放在排序前面？",
            ["先篩選，才能讓**組內每一組候選配對都被檢定**。如果先排序再截斷，"
             "距離整體偏大的組可能一組都輪不到。所以我不設候選截斷。"],
            style="plain", size=14)
    callout(s, 6.85, 4.70, 5.75, 1.6, "五個來源只在第 2 層不同",
            ["其餘三層完全相同 → 任兩個來源之間**只有一個變因**。"
             "交易端也一樣：同一批配對，只換交易端。"], style="light", size=14)
    return """
形成期我拆成四層，每一層都可以單獨換掉。

第一層是特徵萃取，19 維。第二層是分組，也就是紅色這塊——它是唯一有差異的一層，提供五個配對來源。第三層是統計篩選，做共整合檢定。第四層是群內排序，用距離挑出最像的前 N 組。

左下有一個設計細節我想講：為什麼篩選要放在排序前面？如果先排序、只拿距離最近的幾組去檢定、然後截斷，那距離整體比較大的那些組，可能一組配對都輪不到被檢定。所以我先讓組內每一組候選都受檢，而且不設候選截斷。

右下是這個架構的目的：五個來源只在第二層不同，其他三層完全一樣，所以任兩個來源之間只有一個變因。接下來我照論文的節次，一層一層很快帶過。
"""


