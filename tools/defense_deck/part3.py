@reg(1.0, part=2)
def four_layers(d):
    s = std(d, L + "§3.2.1", "形成期拆成四層，每一層都可以單獨換掉")
    layers = [("1　特徵萃取", ["19 維", "報酬 PCA 5 維", "市值、盈餘殖利率", "GICS one-hot"]),
              ("2　分組", ["5 個配對來源", "不分組／GICS", "HDBSCAN", "Agglomerative／K-means"]),
              ("3　統計篩選", ["Engle-Granger 共整合", "ADF 殘差檢定", "MacKinnon 臨界值"]),
              ("4　群內排序", ["SSD／DTW／SDP", "取距離最小的", "前 N 組"])]
    x = LEFT
    for i, (head, lines) in enumerate(layers):
        col = ACCENT if i == 1 else NAVY
        box(s, x, 1.95, 2.75, 2.45, [{"text": head, "size": 17, "bold": True,
                                      "color": WHITE, "after": 8}] +
            [{"text": t, "size": 13.5, "color": WHITE, "after": 2} for t in lines],
            fill=col)
        if i < 3:
            arrow(s, x + 2.77, 3.17, x + 3.03, 3.17, color=GREY, width=2.0)
        x += 3.05
    callout(s, LEFT, 4.70, 5.75, 1.6, "為什麼篩選要放在排序前面？",
            ["先篩選，才能讓**組內每一組候選配對都被檢定**。如果先排序再截斷，"
             "距離整體偏大的組可能一組都輪不到。所以我不設候選截斷。"],
            style="plain", size=14)
    callout(s, 6.85, 4.70, 5.75, 1.6, "五個來源只在第 2 層不同",
            ["其餘三層完全相同 → 任兩個來源之間**只有一個變因**。"
             "交易端也一樣：同一批配對，只換交易端。"], style="light", size=14)
    return """
形成期我拆成四層，每一層都可以單獨換掉。

第一層是特徵萃取，19 維。第二層是分組，也就是紅色這塊——它是唯一有差異的一層，提供五個配對來源。第三層是統計篩選，做共整合檢定。第四層是群內排序，用距離挑出最像的前 N 組。

左下有一個設計細節我想講：為什麼篩選要放在排序前面？如果先排序、只拿距離最近的幾組去檢定、然後截斷，那距離整體比較大的那些組，可能一組配對都輪不到被檢定。所以我先讓組內每一組候選都受檢，而且不設候選截斷。

右下是這個架構的目的：五個來源只在第二層不同，其他三層完全一樣，所以任兩個來源之間只有一個變因。接下來我一層一層很快帶過。
"""


